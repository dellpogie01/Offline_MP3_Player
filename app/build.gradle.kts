// Java's Windows argument-file encoding can corrupt non-ASCII classpath entries.
// A manifest uses percent-encoded URLs and keeps the worker argument path ASCII.
if (System.getProperty("os.name").startsWith("Windows") && rootDir.path.any { it.code > 127 }) {
  afterEvaluate {
   tasks.withType<Test>().forEach { testTask ->
    val runtimeClasspath = testTask.classpath
    testTask.inputs.files(runtimeClasspath).withPropertyName("originalRuntimeClasspath")
      .withNormalizer(org.gradle.api.tasks.ClasspathNormalizer::class.java)
    val classpathJar = tasks.register<Jar>("${testTask.name}ClasspathJar") {
      dependsOn(runtimeClasspath)
      destinationDirectory.set(file(System.getProperty("java.io.tmpdir"))
        .resolve("sonicbeat-tests-${rootDir.path.hashCode()}"))
      archiveFileName.set("${testTask.name}-classpath.jar")
      inputs.files(runtimeClasspath)
      doFirst {
        manifest.attributes("Class-Path" to runtimeClasspath.files.joinToString(" ") {
          it.toURI().toASCIIString()
        })
      }
    }
    testTask.classpath = files(classpathJar.flatMap { it.archiveFile })
   }
  }
}

